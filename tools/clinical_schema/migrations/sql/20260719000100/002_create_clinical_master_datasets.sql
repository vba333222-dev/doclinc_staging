CREATE TABLE `clinical_master_datasets` (
  `clinical_master_dataset_id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `clinical_master_package_id` BIGINT UNSIGNED NOT NULL,
  `dataset_key` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `source_file` VARCHAR(255) COLLATE utf8mb4_bin NOT NULL,
  `dataset_version` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `dataset_checksum` CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `domain_key` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `entity_key` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  `source_governance_status` VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `governance_status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'unreviewed',
  `source_runtime_enabled` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `license_disposition` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'not_declared',
  `declared_record_count` BIGINT UNSIGNED NOT NULL,
  `observed_record_count` BIGINT UNSIGNED NOT NULL,
  `seed_order` SMALLINT UNSIGNED NOT NULL,
  `natural_key_contract` VARCHAR(255) COLLATE utf8mb4_bin NULL,
  `hierarchy_mode` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'none',
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`clinical_master_dataset_id`),
  UNIQUE KEY `uq_clinical_master_dataset_package_key` (`clinical_master_package_id`, `dataset_key`),
  UNIQUE KEY `uq_clinical_master_dataset_package_seed` (`clinical_master_package_id`, `seed_order`),
  KEY `idx_clinical_master_dataset_governance` (`governance_status`),
  KEY `idx_clinical_master_dataset_license` (`license_disposition`),
  KEY `idx_clinical_master_dataset_domain` (`domain_key`),
  KEY `idx_clinical_master_dataset_checksum` (`dataset_checksum`),
  CONSTRAINT `fk_clinical_master_dataset_package` FOREIGN KEY (`clinical_master_package_id`) REFERENCES `clinical_master_packages` (`clinical_master_package_id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT `chk_clinical_master_dataset_checksum` CHECK (`dataset_checksum` REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT `chk_clinical_master_dataset_governance` CHECK (`governance_status` IN ('unreviewed','in_review','approved','rejected','retired')),
  CONSTRAINT `chk_clinical_master_dataset_license` CHECK (`license_disposition` IN ('not_declared','review_required','cleared','restricted','rejected')),
  CONSTRAINT `chk_clinical_master_dataset_runtime` CHECK (`source_runtime_enabled` IN (0,1)),
  CONSTRAINT `chk_clinical_master_dataset_hierarchy` CHECK (`hierarchy_mode` IN ('none','tree','dag','self_parent')),
  CONSTRAINT `chk_clinical_master_dataset_source_file` CHECK (`source_file` <> '' AND OCTET_LENGTH(`source_file`) = OCTET_LENGTH(TRIM(`source_file`)) AND !(`source_file` REGEXP '[[:cntrl:]]') AND LEFT(`source_file`,1) <> '/' AND LOCATE(CONVERT(CHAR(92) USING utf8mb4),`source_file`) = 0 AND !(`source_file` REGEXP '^[A-Za-z][A-Za-z0-9+.-]*:') AND `source_file` <> '.' AND `source_file` <> '..' AND `source_file` NOT LIKE '../%' AND `source_file` NOT LIKE '%/../%' AND `source_file` NOT LIKE '%/..')
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_general_ci;
