CREATE TABLE `clinical_master_dataset_field_contracts` (
  `clinical_master_dataset_field_contract_id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `clinical_master_dataset_id` BIGINT UNSIGNED NOT NULL,
  `source_field` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `source_json_type` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `cardinality` VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `required_flag` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `nullable_flag` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  `identity_role` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'none',
  `target_domain` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  `target_entity` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  `target_attribute` VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
  `transform_policy` VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'blocked',
  `contract_status` VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'draft',
  `review_reason` VARCHAR(1000) NULL,
  `decision_actor` VARCHAR(128) COLLATE utf8mb4_bin NULL,
  `decided_at` DATETIME(6) NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`clinical_master_dataset_field_contract_id`),
  UNIQUE KEY `uq_clinical_master_field_contract_dataset_field` (`clinical_master_dataset_id`, `source_field`),
  KEY `idx_clinical_master_field_contract_dataset` (`clinical_master_dataset_id`),
  KEY `idx_clinical_master_field_contract_status` (`contract_status`),
  KEY `idx_clinical_master_field_contract_identity` (`identity_role`),
  KEY `idx_clinical_master_field_contract_target` (`target_domain`, `target_entity`),
  CONSTRAINT `fk_clinical_master_field_contract_dataset` FOREIGN KEY (`clinical_master_dataset_id`) REFERENCES `clinical_master_datasets` (`clinical_master_dataset_id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT `chk_clinical_master_field_contract_json_type` CHECK (`source_json_type` IN ('string','integer','number','boolean','object','array','null','mixed')),
  CONSTRAINT `chk_clinical_master_field_contract_cardinality` CHECK (`cardinality` IN ('scalar','array')),
  CONSTRAINT `chk_clinical_master_field_contract_booleans` CHECK (`required_flag` IN (0,1) AND `nullable_flag` IN (0,1)),
  CONSTRAINT `chk_clinical_master_field_contract_identity` CHECK (`identity_role` IN ('none','primary_code','natural_key_component','parent_reference','label','provenance')),
  CONSTRAINT `chk_clinical_master_field_contract_transform` CHECK (`transform_policy` IN ('identity','trim_only','unicode_nfc','lookup_fk','array_expand','manual_review','blocked')),
  CONSTRAINT `chk_clinical_master_field_contract_status` CHECK (`contract_status` IN ('draft','in_review','approved','rejected','retired')),
  CONSTRAINT `chk_clinical_master_field_contract_approval` CHECK (`contract_status` <> 'approved' OR `decision_actor` IS NOT NULL AND `decision_actor` <> '' AND `decided_at` IS NOT NULL AND `transform_policy` <> 'blocked'),
  CONSTRAINT `chk_clinical_master_field_contract_source_field` CHECK (`source_field` REGEXP '^[A-Za-z_][A-Za-z0-9_]*$'),
  CONSTRAINT `chk_clinical_master_field_contract_target_domain` CHECK (`target_domain` IS NULL OR `target_domain` REGEXP '^[a-z][a-z0-9_]*$'),
  CONSTRAINT `chk_clinical_master_field_contract_target_entity` CHECK (`target_entity` IS NULL OR `target_entity` REGEXP '^[a-z][a-z0-9_]*$'),
  CONSTRAINT `chk_clinical_master_field_contract_target_attribute` CHECK (`target_attribute` IS NULL OR `target_attribute` REGEXP '^[a-z][a-z0-9_]*$')
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8mb4 COLLATE=utf8mb4_general_ci;
